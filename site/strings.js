let current = 'nan';

export const language = () => current;

// Unknown values keep the default, so a stale stored setting cannot break the page.
export function setLanguage(lang) {
  current = LANGUAGES.includes(lang) ? lang : 'nan';
}

// The text for `key` with {name} placeholders filled; a key missing in ja / en falls back to nan.
export function t(key, params = {}) {
  const template = STRINGS[current][key] ?? STRINGS.nan[key];
  if (template === undefined) throw new Error(`strings: unknown key "${key}"`);
  return template.replace(/\{(\w+)\}/g, (_, name) => String(params[name]));
}

// The same, as a list of strings and the given nodes, for text with an element inside (a link).
export function tParts(key, params = {}) {
  const template = STRINGS[current][key] ?? STRINGS.nan[key];
  return template.split(/(\{\w+\})/).filter(Boolean).map((part) => {
    const name = /^\{(\w+)\}$/.exec(part)?.[1];
    return name === undefined ? part : params[name];
  });
}

export const formatNumber = (n) => n.toLocaleString('en-US');
export const listJoin = (items) => items.join(t('list.separator'));
export const sentenceJoin = (items) => items.join(t('list.sentences'));

// A site tag's label in the reader's language; contributors' own tags keep their name.
const TAG_BY_NAME = new Map(TAGS.map((tag) => [tag.name, tag]));
export const tagLabel = (name) => (current === 'nan' ? name : (TAG_BY_NAME.get(name)?.[current] ?? name));

// A validation issue (lib/entry.js issue codes) as one line for the field it sits under:
// { field, example?, text }, `example` being the index of the example row. Identity fields are
// filled in by the Worker and never shown.
const HIDDEN_FIELDS = new Set(['contributor', 'contributor_id', 'submitted']);
export function describeIssues(issues) {
  return issues
    .filter((found) => !HIDDEN_FIELDS.has(found.field))
    .map((found) => {
      const key = `issue.${found.code}`;
      let message = STRINGS.nan[key] === undefined ? t('issue.other') : t(key, found);
      // a missing value reads 「請填寫資料」 alone: the line sits under the empty field
      if (found.code === 'required') return { field: found.field, text: message };
      if (found.tag !== undefined) message = t('issue.withTag', { tag: found.tag, message });
      const example = /^examples\[(\d+)\]\.(hanji|tl)$/.exec(found.field);
      if (example) {
        const field = t('field.example', { field: t(`field.${example[2]}`) });
        return { field: example[2], example: Number(example[1]), text: t('issue.withField', { field, message }) };
      }
      const label = STRINGS.nan[`field.${found.field}`] === undefined ? found.field : t(`field.${found.field}`);
      return { field: found.field, text: t('issue.withField', { field: label, message }) };
    });
}
